// R2 + R3/R4, at the level the harness itself is built: no network, no listener, one
// `RunnerSettings` triple pointed at a port nothing serves (a preset `create()` never
// dials the provider, so a dead baseURL is correct here and proves no accidental call).
import { describe, expect, it } from 'vitest';
import { createHarnessRegistry, presets } from '@underload/harness/server';
import {
    EDITOR_AGENT_NAME,
    EDITOR_INSTRUCTION,
    READER_AGENT_NAME,
    READER_INSTRUCTION,
    STORYLINE_AGENT_COLORS,
    STORYLINE_AGENT_INSTRUCTIONS,
    STORYLINE_AGENT_NAMES,
    STORYLINE_PRESET_NAME,
    WRITER_AGENT_NAME,
    WRITER_INSTRUCTION,
    createStorylineHarnessRegistry,
    createStorylinePreset,
    enableStorylineRecordTools,
    ensureStorylinePreset
} from './presets';

// A fresh harness per test: the record ids are generated by the session's record
// engine and are UNIQUE ACROSS COLLECTIONS in one harness, so `chapters.add` then
// `profiles.add` yields ids '1' and '2' in that order. A shared harness would make
// those exact assertions depend on test order.
const SETTINGS = { baseURL: 'http://127.0.0.1:1/v1', apiKey: '', model: 'story/test-model' };

const buildStorylineHarness = () => createStorylinePreset().create(SETTINGS, () => {});

// `updatedAt` is a wall-clock stamp, so it is the only field removed before an exact
// comparison — every remaining field is deterministic and asserted in full.
const withoutTimestamp = <T extends { updatedAt?: unknown }>(value: T): Omit<T, 'updatedAt'> => {
    const { updatedAt: _ignored, ...rest } = value;

    return rest;
};

describe('storyline preset metadata', () => {
    it('names the roster exactly: writer primary, reader and editor delegated', () => {
        const preset = createStorylinePreset();

        expect(preset.name).toBe(STORYLINE_PRESET_NAME);
        expect(preset.title).toBe('Storyline');
        expect(preset.primary).toBe(WRITER_AGENT_NAME);
        expect(preset.subagents).toEqual([READER_AGENT_NAME, EDITOR_AGENT_NAME]);
        expect(preset.agents).toEqual([...STORYLINE_AGENT_NAMES]);
        // A live, endpoint-backed card: `requiresEndpoint` is what stops the
        // descriptor from promising an offline harness.
        expect(preset.requiresEndpoint).toBe(true);
        expect(preset.template).toBe('live');
        expect(preset.builtin).toBe(true);
        expect(preset.editable).toBe(true);
        // The two collections this package guarantees, and nothing else beyond the
        // shared toolbox the harness advertises on every card.
        expect(preset.environmentTools).toEqual(['search', 'fetch']);
        expect(preset.customAgents).toEqual(STORYLINE_AGENT_INSTRUCTIONS);
        expect(preset.agentColors).toEqual(STORYLINE_AGENT_COLORS);
        expect(preset.tools).toContain('read');
        expect(preset.tools).toContain('write');
    });

    it('gives every member its own prompt, and only that prompt', () => {
        const harness = buildStorylineHarness();

        expect(Object.keys(harness.agents)).toEqual(['writer', 'reader', 'editor']);
        expect(harness.name).toBe(WRITER_AGENT_NAME);
        expect(Object.keys(harness.subagents)).toEqual(['reader', 'editor']);

        // `customAgents` means "no catalogue profile": the stored text IS the whole
        // system message, so an exact match here is also proof the harness did not
        // fall back to a shipped role's guidelines.
        expect(harness.agents[WRITER_AGENT_NAME].messages[0]).toEqual({
            role: 'system',
            content: WRITER_INSTRUCTION,
            messageId: 'msg-1'
        });
        expect(harness.agents[READER_AGENT_NAME].messages[0].content).toBe(READER_INSTRUCTION);
        expect(harness.agents[EDITOR_AGENT_NAME].messages[0].content).toBe(EDITOR_INSTRUCTION);

        // The prompts are distinct: one instruction reused three times would make the
        // team a single voice wearing three names.
        expect(new Set([WRITER_INSTRUCTION, READER_INSTRUCTION, EDITOR_INSTRUCTION]).size).toBe(3);
    });

    it('tells each member the Title model, the compare-and-swap rule and the cast rule (R-D)', () => {
        const prompts: Record<string, string> = { writer: WRITER_INSTRUCTION, reader: READER_INSTRUCTION, editor: EDITOR_INSTRUCTION };

        for (const [agentName, instruction] of Object.entries(prompts)) {
            // The four collections ARE the Title — each prompt names all four by tool name, so
            // no agent has to guess where a plan or a running line lives.
            for (const collection of ['`chapters`', '`profiles`', '`outlines`', '`storyline`']) {
                expect(instruction, `${agentName} names ${collection}`).toContain(collection);
            }

            // No UI or server vocabulary: an agent is told about records and prose, never about
            // the panels a human uses to read them. (A word list rather than one long regex, so
            // a failure names the word that leaked.)
            for (const leaked of ['panel', 'sidebar', 'dashboard', 'browser', 'session', 'thread', 'endpoint', 'stream']) {
                expect(instruction.toLowerCase(), `${agentName} says "${leaked}"`).not.toContain(leaked);
            }
        }

        // The exact sentences that carry the two behaviours the UI cannot enforce. Pinned whole
        // because a paraphrase loses the part that makes them actionable: the rev token's shape,
        // and the two trait values the folder list renders as (F)/(M).
        expect(WRITER_INSTRUCTION.split('\n')).toContain(
            'Read a record before you change it, and send the `rev` you read back as `expects: [{ id, rev }]`; a rejected write means somebody else moved first, so re-read and re-apply instead of forcing.'
        );
        expect(EDITOR_INSTRUCTION.split('\n')).toContain(
            'Every write carries `expects: [{ id, rev }]` for the revision you just read; a rejected call means re-read and re-apply, never force.'
        );
        expect(WRITER_INSTRUCTION.split('\n')).toContain(
            'Keep the cast in `profiles`, and give every character a gender trait — `female` or `male` — the moment the character is created. Never leave one without it.'
        );
        expect(EDITOR_INSTRUCTION.split('\n')).toContain(
            'Repair the cast through `profiles`: merge duplicate characters, resolve contradictory traits, and give any profile without a gender trait one — `female` or `male` — because a character without it is unfinished.'
        );
        // The reader is read-only by policy, and only its own prompt can say so.
        expect(READER_INSTRUCTION.split('\n')[0]).toBe('You are the reader: you read the Title and critique it. You never rewrite it and you change no record.');
        // Ordered sections, not one blob: the writer is told the bound the collection enforces,
        // and the editor is told a revision patches a section rather than rewriting the Title.
        expect(WRITER_INSTRUCTION.split('\n')).toContain(
            'A chapter body goes in `chapters.content`, which holds 4000 characters: split a scene that runs longer into chapters instead of cutting it short, and let `order` say where each chapter belongs.'
        );
        expect(EDITOR_INSTRUCTION.split('\n')).toContain(
            'Keep `outlines` and `storyline` current through the `records` tool with `collection: "outlines"` or `collection: "storyline"`: they are ordered sections, so a revision is an entry carrying that section\'s `id` and only the fields you changed, and a new section is an entry with no `id` — never a rewrite of the whole document.'
        );
        // The role split the chain depends on: the writer writes prose, the editor revises the
        // shape, and neither claims the other's job.
        expect(WRITER_INSTRUCTION.split('\n')[0]).toBe('You are the writer, the primary agent of a story team, and the only member who writes prose.');
        expect(EDITOR_INSTRUCTION.split('\n')[0]).toContain('you revise them in place');
    });

    it('registers the delegation tool, because a non-empty allowlist is what enables it', () => {
        const harness = buildStorylineHarness();

        expect(harness.tools.delegate).toBeDefined();
        expect(harness.tools.delegate.visibility).toBe('core');
    });
});

describe('storyline record tools (R3/R4)', () => {
    it('carries the built-in `chapters` and `profiles` definitions, not copies', () => {
        const harness = buildStorylineHarness();
        const chapters = harness.tools.chapters;
        const profiles = harness.tools.profiles;

        expect(chapters).toBeDefined();
        expect(profiles).toBeDefined();

        // The declared JSON Schema, narrowed to the shape this test reads (the library
        // types `parameters` as an optional unknown, and JSON Schema is the only
        // parameter language the harness accepts — no zod).
        const chapterSchema = chapters.parameters as {
            type: string;
            properties: Record<string, unknown>;
            required?: string[];
        };
        const profileSchema = profiles.parameters as {
            properties: Record<string, unknown>;
            required?: string[];
        };

        // The harness's own collection wrappers: their tags and their searchability
        // are the shipped metadata (packages/underload/harness/src/tools/runtime/
        // {chapters,profiles}.tool.ts). `searchable` is exactly why
        // `enableStorylineRecordTools` has to exist.
        expect(chapters.visibility).toBe('searchable');
        expect(chapterSchema.type).toBe('object');
        expect(Object.keys(chapterSchema.properties)).toEqual([
            'action',
            'id',
            'title',
            'summary',
            'content',
            'status',
            'order',
            'expects',
            'mergeDisjoint',
            'offset',
            'limit',
            'where'
        ]);
        expect(chapterSchema.required).toEqual(['action']);

        expect(profiles.visibility).toBe('searchable');
        expect(Object.keys(profileSchema.properties)).toEqual([
            'action',
            'id',
            'name',
            'description',
            'traits',
            'notes',
            'expects',
            'mergeDisjoint',
            'offset',
            'limit',
            'where'
        ]);
        expect(profileSchema.required).toEqual(['action']);

        // No duplicate was introduced: the registry has ONE entry per name.
        expect(Object.keys(harness.tools).filter((name) => name === 'chapters')).toEqual(['chapters']);
        expect(Object.keys(harness.tools).filter((name) => name === 'profiles')).toEqual(['profiles']);
    });

    it('declares the three record tools from the first turn, with no discovery call by the model', () => {
        const harness = buildStorylineHarness();

        // `discoveredTools` is the enabled SEARCHABLE set the next model request
        // declares. Newest-first is the harness's own rule, so the exact order is
        // records-profiles-chapters (STORYLINE_RECORD_TOOL_NAMES enables chapters first).
        // `records` is in that set because the two collections a Title owns (`outlines`,
        // `storyline`, ./collections.ts) are ordinary record collections: without the tool
        // declared an agent could read them from the UI but never write a section.
        expect(harness.discoveredTools).toEqual(['records', 'profiles', 'chapters']);

        // The declarations are the harness's own, not copies: all three are searchable,
        // which is exactly why they need enabling at all.
        expect((harness.tools.records as { visibility: string }).visibility).toBe('searchable');

        // Enabling again is a no-op: `create()` runs per session, and a session that
        // restores a snapshot with all three enabled must not evict or reorder them.
        enableStorylineRecordTools(harness);

        expect(harness.discoveredTools).toEqual(['records', 'profiles', 'chapters']);

        // The other record collections stay behind discovery, so the guaranteed set is
        // exactly the three ./presets.ts names — `locations` is registered but not declared.
        expect(harness.tools.locations).toBeDefined();
        expect(harness.discoveredTools).not.toContain('locations');
    });

    it('round-trips a chapter through the built-in schema', async () => {
        const harness = buildStorylineHarness();

        const added = (await harness.executeTool('chapters', {
            action: 'add',
            title: 'Chapter One: The Quiet Harbour',
            summary: 'Ines arrives looking for a ship that has already left.',
            content: 'The harbourmaster did not look up from his ledger.',
            status: 'draft',
            order: 10
        })) as { chapter: Record<string, unknown>; counts: Record<string, unknown> };

        expect(withoutTimestamp(added.chapter as { updatedAt: unknown })).toEqual({
            id: '1',
            title: 'Chapter One: The Quiet Harbour',
            summary: 'Ines arrives looking for a ship that has already left.',
            status: 'draft',
            order: 10,
            rev: 1,
            updatedBy: WRITER_AGENT_NAME
        });
        expect(added.counts).toEqual({ total: 1, planned: 0, draft: 1, complete: 0 });

        const listed = (await harness.executeTool('chapters', { action: 'list' })) as {
            chapters: Record<string, unknown>[];
            counts: Record<string, unknown>;
            page: Record<string, unknown>;
        };

        // A list carries the summary, never the body — the collection spec declares
        // `content` as getOnly, and this is the assertion that keeps it that way.
        expect(listed.chapters).toHaveLength(1);
        expect(withoutTimestamp(listed.chapters[0] as { updatedAt: unknown })).toEqual({
            id: '1',
            title: 'Chapter One: The Quiet Harbour',
            summary: 'Ines arrives looking for a ship that has already left.',
            status: 'draft',
            order: 10,
            rev: 1,
            updatedBy: WRITER_AGENT_NAME
        });
        expect(listed.counts).toEqual({ total: 1, planned: 0, draft: 1, complete: 0 });
        expect(listed.page).toEqual({ offset: 0, limit: 20, hasMore: false });

        const fetched = (await harness.executeTool('chapters', { action: 'get', id: '1' })) as {
            chapter: Record<string, unknown>;
            counts: Record<string, unknown>;
            content?: string;
        };

        // The wire shape is `{ chapter, counts, content }`: `content` rides the RESULT
        // of a `get` and never the chapter row, which is how a list can stay body-free
        // without dropping the field from the record (the engine declares it `getOnly`
        // in packages/underload/harness/src/core/chapter.ts:39).
        expect(fetched.content).toBe('The harbourmaster did not look up from his ledger.');
        expect(Object.keys(fetched.chapter)).toEqual([
            'id',
            'title',
            'summary',
            'status',
            'order',
            'rev',
            'updatedBy',
            'updatedAt'
        ]);
    });

    it('round-trips a profile, sharing the id counter with chapters', async () => {
        const harness = buildStorylineHarness();

        // First a chapter, so the shared per-session counter is visible: ids are
        // unique across EVERY collection in one session, not per collection.
        await harness.executeTool('chapters', { action: 'add', title: 'Opening', summary: 'The beginning.' });

        const added = (await harness.executeTool('profiles', {
            action: 'add',
            name: 'Ines Vanderhoeft',
            description: 'A cartographer who trusts tides over maps.',
            traits: ['stubborn', 'observant']
        })) as { profile: Record<string, unknown>; counts: Record<string, unknown> };

        expect(withoutTimestamp(added.profile as { updatedAt: unknown })).toEqual({
            id: '2',
            name: 'Ines Vanderhoeft',
            description: 'A cartographer who trusts tides over maps.',
            traits: ['stubborn', 'observant'],
            notes: '',
            rev: 1,
            updatedBy: WRITER_AGENT_NAME
        });
        expect(added.counts).toEqual({ total: 1 });

        const listed = (await harness.executeTool('profiles', { action: 'list' })) as {
            profiles: Record<string, unknown>[];
            counts: Record<string, unknown>;
            page: Record<string, unknown>;
        };

        expect(listed.profiles).toHaveLength(1);
        expect(listed.counts).toEqual({ total: 1 });
        expect(listed.page).toEqual({ offset: 0, limit: 20, hasMore: false });

        // A compare-and-swap update with the rev the caller read is accepted, and the
        // rev bumps only when a field actually changes.
        const updated = (await harness.executeTool('profiles', {
            action: 'update',
            id: '2',
            notes: 'She keeps the tide table in her coat.',
            expects: [{ id: '2', rev: 1 }]
        })) as { profile: Record<string, unknown> };

        expect(updated.profile.rev).toBe(2);
        expect(updated.profile.notes).toBe('She keeps the tide table in her coat.');
    });
});

describe('storyline registry (R2)', () => {
    it('seeds the shipped catalogue first and adds `storyline` once', () => {
        const registry = createStorylineHarnessRegistry();
        const names = registry.list().map((preset) => preset.name);

        expect(names.slice(0, presets.length)).toEqual(presets.map((preset) => preset.name));
        expect(names).toContain(STORYLINE_PRESET_NAME);

        const storyline = registry.find(STORYLINE_PRESET_NAME);

        expect(storyline).toBeDefined();
        expect(storyline?.primary).toBe(WRITER_AGENT_NAME);
        expect(storyline?.subagents).toEqual([READER_AGENT_NAME, EDITOR_AGENT_NAME]);
    });

    it('honours `includeShipped: false` — the card list is then exactly ours', () => {
        const registry = createStorylineHarnessRegistry({ includeShipped: false });

        expect(registry.list().map((preset) => preset.name)).toEqual([STORYLINE_PRESET_NAME]);
    });

    it('lets a later preset of the same name win (a scripted session in a wider host)', () => {
        const scripted = createStorylinePreset();
        scripted.title = 'Storyline (scripted)';

        const registry = createStorylineHarnessRegistry({ extra: [scripted] });

        expect(registry.find(STORYLINE_PRESET_NAME)?.title).toBe('Storyline (scripted)');
    });

    it('adds the preset to a registry that was built without it', () => {
        // The wider-gateway case: the root-keyed runtime already exists with the
        // default catalogue, so `ensureStorylinePreset` is the only way a storyline
        // session can be created there.
        const registry = createHarnessRegistry();

        expect(registry.find(STORYLINE_PRESET_NAME)).toBeUndefined();

        const preset = ensureStorylinePreset(registry);

        expect(preset.name).toBe(STORYLINE_PRESET_NAME);
        expect(registry.find(STORYLINE_PRESET_NAME)).toBe(preset);
        // Idempotent: a second call cannot append a duplicate or replace the live one.
        expect(ensureStorylinePreset(registry)).toBe(preset);
        expect(registry.list().filter((entry) => entry.name === STORYLINE_PRESET_NAME)).toHaveLength(1);
    });

    it('returns the existing preset untouched when one is already registered', () => {
        const registry = createStorylineHarnessRegistry();
        const before = registry.find(STORYLINE_PRESET_NAME);

        expect(ensureStorylinePreset(registry)).toBe(before);
    });
});
